#!/usr/bin/env python3
"""Write src/fft/kiss_fft960_tables.h: constant twiddles for the forward 960-point real FFT
(480-point complex FFT + 240 real-FFT super twiddles), so they live in flash instead of RAM.
Values match kf_cexp(): (float)cos(phase), (float)sin(phase) computed in double."""
import math, struct
from pathlib import Path

def f32(x):
    return struct.unpack('f', struct.pack('f', x))[0]

def fmt(x):
    return repr(f32(x)) + 'f'

N = 480
tw = [-2 * math.pi * i / N for i in range(N)]
sup = [-math.pi * ((i + 1) / N + .5) for i in range(N // 2)]
out = ["// Generated by tools/gen_fft960_tables.py - do not edit by hand.",
       "#ifndef KISS_FFT960_TABLES_H", "#define KISS_FFT960_TABLES_H", "",
       f"#define KFFT_TABLE_N {N}", "",
       "static const kiss_fft_cpx kfft480_twiddles[KFFT_TABLE_N] = {"]
out += ["    {%s, %s}," % (fmt(math.cos(p)), fmt(math.sin(p))) for p in tw]
out += ["};", "", "static const kiss_fft_cpx kfftr960_super_twiddles[KFFT_TABLE_N / 2] = {"]
out += ["    {%s, %s}," % (fmt(math.cos(p)), fmt(math.sin(p))) for p in sup]
out += ["};", "", "#endif", ""]
Path(__file__).resolve().parent.parent.joinpath("src/fft/kiss_fft960_tables.h").write_text("\n".join(out))
