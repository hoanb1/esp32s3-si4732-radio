#!/usr/bin/env python3
"""Pack webui/index.html into ats-mini/WebUI.h as a gzip byte array.

Run after editing index.html:  python3 webui/build_webui.py
The firmware serves the bytes as-is with Content-Encoding: gzip and an ETag,
so browsers download ~15 KB once and then get 304 Not Modified.
"""
import gzip
import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "index.html"
DST = ROOT.parent / "ats-mini" / "WebUI.h"


def minify(html: str) -> str:
    html = re.sub(r"<!--.*?-->", "", html, flags=re.S)
    out = []
    for line in html.splitlines():
        s = line.strip()
        # Whole-line JS comments only; inline // may be part of a URL or string
        if not s or s.startswith("//"):
            continue
        out.append(s)
    return "\n".join(out)


def main() -> None:
    raw = SRC.read_text(encoding="utf-8")
    data = gzip.compress(minify(raw).encode("utf-8"), compresslevel=9, mtime=0)
    etag = hashlib.sha1(data).hexdigest()[:12]
    rows = []
    for i in range(0, len(data), 20):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    DST.write_text(
        "// Generated by webui/build_webui.py from webui/index.html - do not edit by hand.\n"
        "#ifndef WEBUI_H\n#define WEBUI_H\n\n#include <Arduino.h>\n\n"
        f'#define WEBUI_ETAG "\\"{etag}\\""\n\n'
        f"const size_t WEBUI_HTML_GZ_LEN = {len(data)};\n"
        "const uint8_t WEBUI_HTML_GZ[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n\n#endif\n",
        encoding="utf-8",
    )
    print(f"{SRC.name}: {len(raw)} B -> gzip {len(data)} B, ETag {etag} -> {DST}")


if __name__ == "__main__":
    main()
