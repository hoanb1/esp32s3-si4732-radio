#!/usr/bin/env python3
"""Build the web UI world map: Natural Earth 1:110m countries -> compact SVG -> gzip -> ats-mini/WorldMap.h.

Source data (public domain): https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json
Usage:  python3 webui/build_worldmap.py countries-110m.json

Equirectangular projection, 2 SVG units per degree: x = (lon + 180) * 2, y = (90 - lat) * 2 (720 x 360).
Three paths: land (filled), coast (arcs used by one country) and borders (arcs shared by two).
Lines crossing the date line are unwrapped past 0..720, so the page draws the map at -720, 0 and +720.
"""
import gzip
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DST = ROOT.parent / "ats-mini" / "WorldMap.h"
K = 2.0      # SVG units per degree
Q = 5        # coordinates are stored in 1/Q units (0.1 degree)


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            lon, lat = x * sx + tx, y * sy + ty
            pts.append((round((lon + 180) * K * Q), round((90 - lat) * K * Q)))
        arcs.append(pts)
    return arcs


def arc_points(arcs, i):
    return arcs[i] if i >= 0 else arcs[~i][::-1]


def unwrap(pts):
    """Keep a line continuous across the date line (x may leave 0..720; the page draws the map three times)."""
    out = []
    shift = 0
    for j, (x, y) in enumerate(pts):
        if j:
            d = x + shift - out[-1][0]
            if d > 180 * K * Q:
                shift -= 360 * K * Q
            elif d < -180 * K * Q:
                shift += 360 * K * Q
        out.append((x + shift, y))
    return out


def path_d(lines, close):
    """Relative SVG path; consecutive duplicate points dropped."""
    out = []
    for pts in lines:
        pts = unwrap(pts)
        clean = [p for j, p in enumerate(pts) if j == 0 or p != pts[j - 1]]
        if len(clean) < 2:
            continue
        x0, y0 = clean[0]
        seg = [f"M{x0 / Q:g} {y0 / Q:g}"]
        rel = []
        px, py = x0, y0
        for x, y in clean[1:]:
            rel.append(f"{(x - px) / Q:g} {(y - py) / Q:g}")
            px, py = x, y
        seg.append("l" + " ".join(rel))
        if close:
            seg.append("z")
        out.append("".join(seg))
    return "".join(out).replace(" -", "-")


def main():
    topo = json.loads(Path(sys.argv[1]).read_text())
    arcs = decode_arcs(topo)
    rings = []
    use = {}
    for geom in topo["objects"]["countries"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]] if geom["type"] == "Polygon" else []
        for poly in polys:
            for ring in poly:
                pts = []
                for i in ring:
                    a = arc_points(arcs, i)
                    pts.extend(a if not pts else a[1:])
                    use[i if i >= 0 else ~i] = use.get(i if i >= 0 else ~i, 0) + 1
                rings.append(pts)
    coast = [arcs[i] for i, n in use.items() if n == 1]
    border = [arcs[i] for i, n in use.items() if n > 1]

    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 360">'
        f'<path class="land" d="{path_d(rings, True)}"/>'
        f'<path class="coast" d="{path_d(coast, False)}"/>'
        f'<path class="border" d="{path_d(border, False)}"/>'
        "</svg>"
    )
    gz = gzip.compress(svg.encode(), 9, mtime=0)
    rows = [",".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
    DST.write_text(
        "// Generated by webui/build_worldmap.py from Natural Earth 1:110m (public domain) - do not edit by hand.\n"
        "#ifndef WORLDMAP_H\n#define WORLDMAP_H\n\n#include <Arduino.h>\n\n"
        f'#define WORLDMAP_ETAG "\\"{hashlib.sha1(gz).hexdigest()[:12]}\\""\n\n'
        f"const size_t WORLDMAP_SVG_GZ_LEN = {len(gz)};\n"
        "const uint8_t WORLDMAP_SVG_GZ[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n\n#endif\n"
    )
    print(f"world map: {len(svg)} B -> gzip {len(gz)} B -> {DST}")


if __name__ == "__main__":
    main()
